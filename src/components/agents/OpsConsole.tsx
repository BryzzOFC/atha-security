"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import { useLang } from "@/lib/lang";

/**
 * ATHA Ops Console — live control surface for the REAL agent system.
 *
 * When the site runs on a Node server (dev / standalone) every button spawns
 * the real Python agents (atha-os-live/) and prints their REAL results.
 * When the page is served from the static GitHub Pages export the API is
 * absent by design, and the console falls back to the last baked real
 * report (/atha/report.json) — clearly labelled as offline evidence.
 */

type Severity = "critical" | "high" | "medium" | "low" | "info";

type Finding = {
  severity?: Severity | string;
  type?: string;
  target?: string;
  component?: string;
  description?: string;
  line?: number;
  real_action?: boolean;
  simulated?: boolean;
};

type ApiResult = {
  success?: boolean;
  error?: string;
  agents_registered?: number;
  real_mode?: boolean;
  stats?: Record<string, unknown> | null;
  target?: string;
  generated_by?: string;
  scans?: Record<string, Record<string, unknown>>;
  drift?: Record<string, unknown>;
  sensitive_inventory?: { risky_world_readable?: string[] };
  backups?: string[];
  findings?: Finding[];
  total?: number;
  files_scanned?: number;
  open_ports?: number[];
  status?: string;
  steps_executed?: number;
  total_steps?: number;
  teams_involved?: string[];
  steps_by_team?: Record<string, { step?: string; agent?: string; success?: boolean }[]>;
  total_findings?: number;
  failures?: { agent?: string; step?: string; error?: string }[];
  results?: { agent?: string; step?: string; success?: boolean }[];
  assessment?: string;
  workflow_id?: string;
  reason?: string;
};

const SEV_COLOR: Record<string, string> = {
  critical: "text-red-400 border-red-400/40 bg-red-400/10",
  high: "text-red-300 border-red-300/40 bg-red-300/10",
  medium: "text-amber-300 border-amber-300/40 bg-amber-300/10",
  low: "text-sky-300 border-sky-300/40 bg-sky-300/10",
  info: "text-neutral-400 border-neutral-400/30 bg-neutral-400/10",
};

